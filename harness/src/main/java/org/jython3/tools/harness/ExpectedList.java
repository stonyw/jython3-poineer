package org.jython3.tools.harness;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * Known-outcome lists, one per backend: {@code harness/expected/<backend>.txt}.
 *
 * <p>Line format, whitespace-separated, {@code #} starts a comment:
 *
 * <pre>
 *   test_math fail
 *   test_socket skip
 *   [macosx] test_subprocess fail   # fork-safety differs on Darwin
 * </pre>
 *
 * A line with no bracketed platform applies everywhere. Platform scoping replaces 2.7's
 * {@code java}/{@code java.nt}/{@code java.posix} keys, expressed against the platforms we actually CI on.
 */
public record ExpectedList(Map<String, Grading.Expectation> byTest) {

    public static ExpectedList empty() {
        return new ExpectedList(Map.of());
    }

    public Grading.Expectation expectationFor(String test) {
        return byTest.getOrDefault(test, Grading.Expectation.NONE);
    }

    public static ExpectedList read(Path file, String platform) throws IOException {
        if (!Files.isRegularFile(file)) {
            return empty();
        }
        Map<String, Grading.Expectation> m = new LinkedHashMap<>();
        List<String> errors = new ArrayList<>();
        int lineNo = 0;
        for (String raw : Files.readAllLines(file)) {
            lineNo++;
            String line = stripComment(raw).trim();
            if (line.isEmpty()) {
                continue;
            }
            String scope = null;
            if (line.startsWith("[")) {
                int close = line.indexOf(']');
                if (close < 0) {
                    errors.add(file + ":" + lineNo + ": unterminated platform scope");
                    continue;
                }
                scope = line.substring(1, close).trim().toLowerCase(Locale.ROOT);
                line = line.substring(close + 1).trim();
            }
            if (scope != null && !scope.isEmpty() && !scope.equals(platform)) {
                continue;
            }
            String[] fields = line.split("\\s+");
            if (fields.length != 2) {
                errors.add(file + ":" + lineNo + ": expected '<test> <fail|skip>', got: " + line);
                continue;
            }
            if (m.containsKey(fields[0])) {
                errors.add(file + ":" + lineNo + ": duplicate entry for " + fields[0]);
                continue;
            }
            try {
                m.put(fields[0], Grading.Expectation.parse(fields[1]));
            } catch (IllegalArgumentException e) {
                errors.add(file + ":" + lineNo + ": " + e.getMessage());
            }
        }
        if (!errors.isEmpty()) {
            throw new IOException("invalid expected list:\n  " + String.join("\n  ", errors));
        }
        return new ExpectedList(Map.copyOf(m));
    }

    /** Renders in the canonical form {@link #read} accepts, for {@code --update-expected}. */
    public static String render(List<Grading.Graded> graded) {
        StringBuilder sb = new StringBuilder();
        sb.append("# Generated by harness --update-expected. Do not hand-edit blind: every entry\n");
        sb.append("# here is a claim that the next run must produce exactly this outcome.\n");
        graded.stream()
                .filter(g -> g.expectation() != Grading.Expectation.NONE)
                .forEach(
                        g ->
                                sb.append(g.result().test())
                                        .append(' ')
                                        .append(
                                                g.expectation() == Grading.Expectation.SKIP
                                                        ? "skip"
                                                        : "fail")
                                        .append('\n'));
        return sb.toString();
    }

    private static String stripComment(String line) {
        int hash = line.indexOf('#');
        return hash < 0 ? line : line.substring(0, hash);
    }

    public static String currentPlatform() {
        String os = System.getProperty("os.name", "").toLowerCase(Locale.ROOT);
        if (os.contains("mac") || os.contains("darwin")) {
            return "macosx";
        }
        if (os.contains("win")) {
            return "windows";
        }
        return "linux";
    }
}
