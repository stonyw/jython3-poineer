def float_bits(v):
    if math.isnan(v):
        return "nan"
    return struct.pack(">d", v).hex()


def render(o, shared=None):
    """A canonical, layout-free description of one unmarshalled object.

    ``shared`` maps the identity of every mutable container to the ordinal it was first visited at;
    revisiting one prints that ordinal instead of a second copy. Only list, dict and set need this
    -- a set or tuple can hold no mutable container as a member, so the numbering order never
    depends on a set's hash-table iteration order.
    """
    if shared is None:
        shared = {}
    if isinstance(o, (list, dict, set)):
        ordinal = shared.get(id(o))
        if ordinal is not None:
            return "#%d" % ordinal
        shared[id(o)] = len(shared)
    if o is None:
        return "None"
    if o is True:
        return "True"
    if o is False:
        return "False"
    if o is Ellipsis:
        return "Ellipsis"
    if isinstance(o, type):
        return "class:" + o.__name__
    if isinstance(o, complex):
        return "complex:%s,%s" % (float_bits(o.real), float_bits(o.imag))
    if isinstance(o, float):
        return "float:" + float_bits(o)
    if isinstance(o, int):
        return "int:%d" % o
    if isinstance(o, (bytes, bytearray)):
        return "bytes:" + bytes(o).hex()
    if isinstance(o, str):
        return "str:" + o.encode("utf-8", "surrogatepass").hex()
    if isinstance(o, tuple):
        return "(" + " ".join(render(x, shared) for x in o) + ")"
    if isinstance(o, list):
        return "[" + " ".join(render(x, shared) for x in o) + "]"
    if isinstance(o, dict):
        return "{" + ", ".join(
            "%s=%s" % (render(k, shared), render(v, shared)) for k, v in o.items()
        ) + "}"
    if isinstance(o, (frozenset, set)):
        # Iteration order of a set is a hash-table artefact; compare the multiset instead.
        prefix = "frozenset(" if isinstance(o, frozenset) else "set("
        return prefix + " ".join(sorted(render(x, shared) for x in o)) + ")"
    if isinstance(o, slice):
        return "slice(%s,%s,%s)" % (
            render(o.start, shared),
            render(o.stop, shared),
            render(o.step, shared),
        )
    if isinstance(o, types.CodeType):
        return render_code(o, shared)
    raise AssertionError("unrenderable %r" % type(o))


def render_code(co, shared):
    lines = [
        "code(argcount=%d,posonly=%d,kwonly=%d,stack=%d,flags=%d,first=%d)"
        % (
            co.co_argcount,
            co.co_posonlyargcount,
            co.co_kwonlyargcount,
            co.co_stacksize,
            co.co_flags,
            co.co_firstlineno,
        ),
        "  file=%s name=%s qualname=%s"
        % (
            co.co_filename.encode("utf-8", "surrogatepass").hex(),
            co.co_name.encode("utf-8", "surrogatepass").hex(),
            co.co_qualname.encode("utf-8", "surrogatepass").hex(),
        ),
        "  wordcode=" + co.co_code.hex(),
        "  linetable=" + co.co_linetable.hex(),
        "  exceptiontable=" + co.co_exceptiontable.hex(),
        # The same bytes, read by CPython's own table parser. dis reports byte offsets and returns
        # ``lasti`` as a bool; the reader under test keeps code units and a bit, and doubles on the
        # way out here rather than anywhere in the interpreter.
        "  exchandles=" + " ".join(
            "%d:%d:%d:%d:%d" % (e.start, e.end, e.target, e.depth, int(e.lasti))
            for e in dis._parse_exception_table(co)
        ),
        "  varnames=%s cellvars=%s freevars=%s nlocals=%d"
        % (
            render(co.co_varnames, shared),
            render(co.co_cellvars, shared),
            render(co.co_freevars, shared),
            co.co_nlocals,
        ),
        "  consts=" + render(co.co_consts, shared),
        "  names=" + render(co.co_names, shared),
        "  decoded="
        + " ".join(
            "%d:%d:%d" % (i.opcode, i.offset, 0 if i.arg is None else i.arg)
            for i in dis.get_instructions(co)
        ),
    ]
    return "\n".join(lines)


def stream_section(name, blob, value):
    return "\n".join([
        "=== " + name,
        "version %d" % MARSHAL_VERSION,
        "data " + blob.hex(),
        "render",
        render(value),
    ])


def error_section(name, blob, exc_name):
    return "\n".join([
        "=== " + name,
        "version %d" % MARSHAL_VERSION,
        "data " + blob.hex(),
        "error " + exc_name,
    ])


def pyc_section(name, blob):
    """A whole .pyc, header included: the container is measured as well as the stream."""
    magic, flags, stamp, size = struct.unpack("<IIII", blob[:16])
    return "\n".join([
        "=== " + name,
        "version %d" % MARSHAL_VERSION,
        "pyc " + blob.hex(),
        "header %08x %d %d %d" % (magic, flags, stamp, size),
        "render",
        render(marshal.loads(blob[16:])),
    ])


def code_sections():
    for name, source in CODE_FIXTURES:
        compiled = compile(source, name + ".py", "exec")
        yield stream_section(name, marshal.dumps(compiled, MARSHAL_VERSION), compiled)
    directory = tempfile.mkdtemp()
    path = os.path.join(directory, "pyc_fixture.py")
    with open(path, "w") as handle:
        handle.write(CODE_FIXTURES[0][1])
    produced = py_compile.compile(
        path, cfile=os.path.join(directory, "pyc_fixture.pyc"), doraise=True
    )
    with open(produced, "rb") as handle:
        yield pyc_section("pyc_module", handle.read())


def object_sections():
    for name, expr in OBJECT_FIXTURES:
        value = eval(expr)
        yield stream_section(name, marshal.dumps(value, MARSHAL_VERSION), value)
    for version in LEGACY_VERSIONS:
        blob = marshal.dumps(eval(LEGACY_OBJECT), version)
        yield stream_section("legacy_v%d" % version, blob, marshal.loads(blob))


def manual_sections():
    for name, blob, expected in MANUAL_FIXTURES:
        try:
            value = marshal.loads(blob)
        except Exception as exc:
            assert expected is not None, "%s: CPython rejected a valid stream: %s" % (name, exc)
            assert type(exc).__name__ == expected, (
                "%s: CPython raised %s, not %s" % (name, type(exc).__name__, expected))
            yield error_section(name, blob, expected)
        else:
            assert expected is None, "%s: CPython accepted a stream meant to fail" % name
            yield stream_section(name, blob, value)


def main():
    if sys.version_info[:2] != (3, 14) or MARSHAL_VERSION != 5:
        sys.exit(
            "these fixtures measure CPython 3.14's marshal version 5; %s at %s writes version %d"
            % (sys.version.split()[0], sys.executable, MARSHAL_VERSION))
    print("# generated by front-cpython314/tools/gen_marshal_fixtures.py -- do not edit, do not commit")
    print("# interpreter: %s (%s)" % (sys.version.split()[0], sys.executable))
    print("# marshal version: %d" % MARSHAL_VERSION)
    print("# a section is one stream: 'data' or 'pyc' carries it, 'render' is what CPython read")
    print("# back from it, 'error' names the exception CPython raised instead.")
    for text in list(code_sections()) + list(object_sections()) + list(manual_sections()):
        print(text)
        print()


if __name__ == "__main__":
    main()

