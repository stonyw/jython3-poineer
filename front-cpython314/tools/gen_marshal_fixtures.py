#!/usr/bin/env python3
"""
Generates the marshal-format fixtures that the Java reader is measured against.

Every expectation in the output is produced by CPython itself, from the same interpreter that
produces the bytes: the hex is what marshal.dumps wrote, and the rendering is CPython's own walk of
the object it read back. That makes the test differential rather than self-referential -- the Java
reader is compared against CPython's reader, not against a transcription of marshal.c.

Two families are emitted. Compiled code objects are what a real ``.pyc`` carries, so they exercise
the format the runtime has to survive; the object fixtures exist because a code object's constants
can only ever be immutable, and TYPE_LIST, TYPE_DICT, TYPE_SET and TYPE_SLICE would otherwise go
untested. The object fixtures also cover sharing and self-reference, which is where a reader that
gets the reference table's allocation order wrong shows up.

Provenance rule (same as the harness): this file is generated, never committed, and must be
regenerated by the interpreter that will run the tests.

    python3.14 front-cpython314/tools/gen_marshal_fixtures.py > out.txt
"""

import dis
import marshal
import math
import os
import py_compile
import struct
import sys
import tempfile
import types

MARSHAL_VERSION = marshal.version

