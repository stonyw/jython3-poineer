#!/usr/bin/env python3.14
"""Prints the cache-size block of InlineCaches.java for the CPython 3.14 interpreter running it.

    front-cpython314/tools/gen_inline_caches.py

and paste everything it prints over the block between the class javadoc and the constructor. The
table cannot be transcribed by hand: a cache unit is indistinguishable from an instruction by its
bytes, so one wrong entry silently misaligns every offset after it — and the marshal fixtures would
then disagree with dis for reasons that look like something else entirely.

Measure the interpreter, never a source checkout: a 3.14 branch checkout is 3.14.9+ development and
already differs from a shipped 3.14 in how many caches some opcodes carry.
"""

import dis
import sys

# 20 per row, 12-space indent — the shape the Java file is kept in.
PER_ROW = 20
INDENT = " " * 12


def main():
    if sys.version_info[:2] != (3, 14):
        sys.exit("this table is CPython 3.14's; this interpreter is %s" % sys.version.split()[0])
    names = dis._all_opname
    sizes = [dis._get_cache_size(names[op]) for op in range(len(names))]
    print("    /** Opcode %d in CPython %s. */" % (dis.opmap["EXTENDED_ARG"], sys.version.split()[0]))
    print("    static final int EXTENDED_ARG = %d;" % dis.opmap["EXTENDED_ARG"])
    print()
    print("    /**")
    print("     * Cache units per opcode number, %d opcodes wide; 0 where there is no cache." % len(sizes))
    print("     *")
    print("     * Generated by {@code tools/gen_inline_caches.py}, do not edit.")
    print("     */")
    print("    private static final int[] SIZE = {")
    for start in range(0, len(sizes), PER_ROW):
        row = sizes[start:start + PER_ROW]
        print(INDENT + ", ".join(str(s) for s in row) + ",")
    print("    };")


if __name__ == "__main__":
    main()
