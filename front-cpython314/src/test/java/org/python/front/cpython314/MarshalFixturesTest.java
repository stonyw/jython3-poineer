package org.python.front.cpython314;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Collection;
import java.util.HexFormat;
import java.util.List;
import org.junit.jupiter.api.DynamicTest;
import org.junit.jupiter.api.TestFactory;

/**
 * Reads every fixture stream CPython wrote and demands the same value CPython read back.
 *
 * The expectation file is generated by {@code tools/gen_marshal_fixtures.py} with the same
 * interpreter that produced the bytes, so a failure here is a difference between two readers rather
 * than between a reader and a transcription of marshal.c. One dynamic test per section, because a
 * mismatch in the twenty-sixth cache table entry is worth naming.
 */
class MarshalFixturesTest {

    /** One section of the expectation file. */
    private record Fixture(
            String name,
            int version,
            byte[] data,
            byte[] pyc,
            String header,
            String error,
            String expected) {
    }

    @TestFactory
    Collection<DynamicTest> readsEveryFixtureStream() {
        List<DynamicTest> tests = new ArrayList<>();
        for (Fixture fixture : load()) {
            tests.add(DynamicTest.dynamicTest(fixture.name(), () -> check(fixture)));
        }
        assertThat(tests).as("sections in the expectation file").isNotEmpty();
        return tests;
    }

    private static void check(Fixture fixture) {
        if (fixture.error() != null) {
            // CPython's own reader raises; the message wording is ours until the exception model
            // lands at M1's end, so what is measured is that this stream is refused.
            assertThatThrownBy(() -> MarshalReader.read(fixture.data()))
                    .as("stream that CPython rejects with " + fixture.error())
                    .isInstanceOf(MarshalFormatException.class);
            return;
        }
        String actual;
        if (fixture.pyc() != null) {
            PycFile file = PycFile.parse(fixture.pyc());
            String[] header = fixture.header().split(" ");
            assertThat(file.magic()).isEqualTo(Integer.parseUnsignedInt(header[0], 16));
            assertThat(file.flags()).isEqualTo(Integer.parseUnsignedInt(header[1]));
            assertThat(file.sourceStamp()).isEqualTo(Long.parseUnsignedLong(header[2]));
            assertThat(file.sourceLength()).isEqualTo(Long.parseUnsignedLong(header[3]));
            actual = MarshalRenderer.render(file.readCode());
        } else {
            actual = MarshalRenderer.render(MarshalReader.read(fixture.data()));
        }
        assertThat(actual).isEqualTo(fixture.expected());
    }

    private static List<Fixture> load() {
        Path path = expectationFile();
        String text;
        try {
            text = Files.readString(path);
        } catch (IOException e) {
            throw new UncheckedIOException("cannot read marshal fixtures " + path, e);
        }
        List<Fixture> fixtures = new ArrayList<>();
        for (String block : text.split("(?m)^=== ")) {
            Fixture fixture = parse(block);
            if (fixture != null) {
                fixtures.add(fixture);
            }
        }
        return fixtures;
    }

    private static Fixture parse(String block) {
        String[] lines = block.split("\n");
        String name = lines[0].trim();
        int version = -1;
        byte[] data = null;
        byte[] pyc = null;
        String header = null;
        String error = null;
        boolean inRender = false;
        StringBuilder body = new StringBuilder();
        for (int i = 1; i < lines.length; i++) {
            String line = lines[i];
            if (inRender) {
                if (!line.isEmpty()) {
                    body.append(line).append('\n');
                }
                continue;
            }
            if (line.startsWith("version ")) {
                version = Integer.parseInt(line.substring(8).trim());
            } else if (line.startsWith("data ")) {
                data = HexFormat.of().parseHex(line.substring(5).trim());
            } else if (line.startsWith("pyc ")) {
                pyc = HexFormat.of().parseHex(line.substring(4).trim());
            } else if (line.startsWith("header ")) {
                header = line.substring(7).trim();
            } else if (line.startsWith("error ")) {
                error = line.substring(6).trim();
            } else if (line.equals("render")) {
                inRender = true;
            }
        }
        if (data == null && pyc == null) {
            return null; // the comment preamble
        }
        assertThat(version).as("marshal version of " + name).isEqualTo(MarshalReader.VERSION);
        assertThat(error == null || data != null).as("an error section carries a data line").isTrue();
        return new Fixture(
                name,
                version,
                data,
                pyc,
                header,
                error,
                // One render line per file line; the renderer itself does not end with a newline.
                inRender ? body.substring(0, Math.max(0, body.length() - 1)) : null);
    }

    private static Path expectationFile() {
        String configured = System.getProperty("jython3.marshalFixtures");
        Path path =
                configured != null
                        ? Path.of(configured)
                        : Path.of("build", "marshal-fixtures.txt");
        if (!Files.isRegularFile(path)) {
            throw new IllegalStateException(
                    "no marshal fixtures at " + path.toAbsolutePath() + "; generate them with "
                            + "'gradle :front-cpython314:syncMarshalFixtures' (the file must come "
                            + "from the same CPython build that reads the fixtures back)");
        }
        return path;
    }
}
