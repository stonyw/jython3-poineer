#!/usr/bin/env python3
"""Export the Unicode name database into org/python/core/unicode-names.txt.gz.

``namereplace`` writes ``\\N{NAME}`` for a character that has a name, and ``unicode_escape`` reads
``\\N{NAME}`` back, so both faces need the same table — the one CPython 3.14.10 ships, not a
transcription.  Two sources, both Unicode 16.0.0:

* primary names, read out of this interpreter's ``unicodedata.name`` — the same call ``namereplace``
  itself answers with, so a character without a name (a surrogate, a private-use value, an
  unassigned one) is left unnamed here too and the handler falls back to ``\\uXXXX``;
* formal aliases from ``NameAliases.txt``, which ``unicodedata.lookup`` (and therefore
  ``\\N{...}``) accepts but never enumerates, plus the algorithmic Tangut ideograph names, which
  ``lookup`` knows and ``name`` does not.

The families whose name is just a prefix and the code point in hex are stored as ranges rather
than as 100,000 lines: CJK unified ideographs (97,668 of them), Khitan, Nushu, and Tangut (the
last decode-only, because ``unicodedata.name`` leaves it unnamed).

    python3.14 runtime/tools/gen_unicode_names.py runtime/src/main/resources/org/python/core/unicode-names.txt.gz
    python3.14 runtime/tools/gen_unicode_names.py --aliases NameAliases-16.0.0.txt OUT

Without ``--aliases`` the alias file is fetched from unicode.org for the version in hand.
"""

import gzip
import io
import sys
import unicodedata
import urllib.request

UNIDATA = "16.0.0"
ALIASES_URL = "https://www.unicode.org/Public/%s/ucd/NameAliases.txt" % UNIDATA

# A name of the form prefix + uppercase hex, which is worth a range instead of one line per value.
ALGORITHMIC = [
    "CJK UNIFIED IDEOGRAPH-",
    "KHITAN SMALL SCRIPT CHARACTER-",
    "NUSHU CHARACTER-",
    "TANGUT IDEOGRAPH-",
]


def check_version() -> None:
    if unicodedata.unidata_version != UNIDATA:
        raise SystemExit(
            "this table belongs to Unicode %s, not %s" % (UNIDATA, unicodedata.unidata_version)
        )


def algorithmic(cp: int, prefix: str) -> str:
    return prefix + "%X" % cp


def ranges(cps) -> list:
    """Maximal runs of consecutive code points, as (first, last) pairs."""
    found = []
    start = previous = cps[0]
    for cp in cps[1:]:
        if cp == previous + 1:
            previous = cp
            continue
        found.append((start, previous))
        start = previous = cp
    found.append((start, previous))
    return found


def read_aliases(path):
    if path is None:
        with urllib.request.urlopen(ALIASES_URL) as answer:
            text = answer.read().decode("utf-8")
        path = "<" + ALIASES_URL + ">"
    else:
        with open(path, encoding="utf-8") as handle:
            text = handle.read()
    aliases = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        code, alias, _kind = line.split(";")
        aliases[alias] = int(code, 16)
    print("aliases from %s: %d" % (path, len(aliases)), file=sys.stderr)
    return aliases


def emit(alias_path):
    named = {}
    for cp in range(0x110000):
        try:
            named[cp] = unicodedata.name(chr(cp))
        except ValueError:
            pass

    # A range the encoder may answer with: name(cp) is exactly the algorithmic spelling.
    encoded = []
    for prefix in ALGORITHMIC:
        cps = sorted(cp for cp, name in named.items() if name == algorithmic(cp, prefix))
        if cps:
            encoded.append((prefix, ranges(cps)))
        named = {
            cp: name for cp, name in named.items() if name != algorithmic(cp, prefix)
        }

    covered = {cp for _prefix, runs in encoded for lo, hi in runs for cp in range(lo, hi + 1)}

    # A range only the decoder may answer with: lookup() finds the spelling, name() has none.
    decoded = []
    for prefix in ALGORITHMIC:
        cps = sorted(
            cp
            for cp in range(0x110000)
            if cp not in named
            and cp not in covered
            and _looks_up(algorithmic(cp, prefix), cp)
        )
        if cps:
            decoded.append((prefix, ranges(cps)))

    aliases = read_aliases(alias_path)
    aliases = {
        alias: cp
        for alias, cp in aliases.items()
        if named.get(cp) != alias and _looks_up(alias, cp)
    }

    lines = [
        "# Unicode names for jy3, generated by runtime/tools/gen_unicode_names.py.",
        "# primary names: CPython %d.%d unicodedata %s (unicodedata.name)" % (*sys.version_info[:2], UNIDATA),
        "# aliases: UCD NameAliases-%s.txt (including the algorithmic names name() does not spell)" % UNIDATA,
        "# name <HEX>;<NAME>       a primary name, both faces",
        "# alias <HEX>;<NAME>      a formal alias, decoder only",
        "# range <LO>-<HI>;<PREFIX>  name = PREFIX + hex, both faces",
        "# decode <LO>-<HI>;<PREFIX>  name = PREFIX + hex, decoder only",
    ]
    lines.extend("name %X;%s" % (cp, name) for cp, name in sorted(named.items()))
    lines.extend("alias %X;%s" % (cp, alias) for alias, cp in sorted(aliases.items(), key=lambda kv: (kv[1], kv[0])))
    lines.extend(
        "range %X-%X;%s" % (lo, hi, prefix) for prefix, runs in encoded for lo, hi in runs
    )
    lines.extend(
        "decode %X-%X;%s" % (lo, hi, prefix) for prefix, runs in decoded for lo, hi in runs
    )
    return "\n".join(lines) + "\n"


def _looks_up(name: str, cp: int) -> bool:
    try:
        return unicodedata.lookup(name) == chr(cp)
    except KeyError:
        return False


def main() -> int:
    check_version()
    arguments = list(sys.argv[1:])
    alias_path = None
    if arguments[:1] == ["--aliases"]:
        alias_path = arguments[1]
        arguments = arguments[2:]
    if len(arguments) != 1:
        print("usage: gen_unicode_names.py [--aliases FILE] OUTPUT", file=sys.stderr)
        return 2
    text = emit(alias_path)
    with open(arguments[0], "wb") as raw:
        with gzip.GzipFile(fileobj=raw, mode="wb", mtime=0) as packed:
            packed.write(text.encode("ascii"))
    print(
        "%s: %d bytes raw, %d bytes gzipped"
        % (arguments[0], len(text.encode("ascii")), len(io.BytesIO(_pack(text)).getvalue())),
        file=sys.stderr,
    )
    return 0


def _pack(text: str) -> bytes:
    buffer = io.BytesIO()
    with gzip.GzipFile(fileobj=buffer, mode="wb", mtime=0) as packed:
        packed.write(text.encode("ascii"))
    return buffer.getvalue()


if __name__ == "__main__":
    raise SystemExit(main())
