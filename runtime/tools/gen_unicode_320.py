#!/usr/bin/env python3
"""Export the Unicode 3.2.0 database into org/python/core/unicode-320.txt.gz.

``unicodedata.ucd_3_2_0`` is a second character database, kept because IDNA and ``stringprep``
(RFC 3454) froze their rules at Unicode 3.2.  It is not the current database under an older version
number: 60,027 code points have a different category, 770 a different decomposition, 607 a different
combining class, and the four normal forms disagree on 116/160/731/775 single code points.  So the
table is exported from the reference's own 3.2.0 reader rather than approximated.

The reference's ``ucd_3_2_0.lookup`` is *not* part of that database: it is the module-wide name
lookup, which CPython builds from the current UCD (it finds ``GRINNING FACE``).  The 95,156 code
points that 3.2.0 names are spelled exactly as 16.0.0 spells them — zero differences over the whole
range — so this file does not repeat the names: it records only which code points 3.2.0 gives a name
to, and the Java side reads the name itself from ``unicode-names.txt.gz`` gated on that set.

What is written:

    range LO-HI;CAT;CCC;BIDI;MIRROR;EAW;NUM;DEC;DIG   maximal runs with the same properties
    decomp HEX;TEXT                                    the raw decomposition() text
    named LO-HI                                        code points name() answers for
    compose A+B;C                                      canonical composition pairs (NFC/NFKC)

    python3.14 runtime/tools/gen_unicode_320.py runtime/src/main/resources/org/python/core/unicode-320.txt.gz
"""

import gzip
import io
import sys
import unicodedata

EXPECTED = "3.2.0"
CURRENT = "16.0.0"


def check() -> None:
    if unicodedata.ucd_3_2_0.unidata_version != EXPECTED:
        raise SystemExit("this table belongs to Unicode %s" % unicodedata.ucd_3_2_0.unidata_version)
    if unicodedata.unidata_version != CURRENT:
        raise SystemExit("the name table this file leans on is Unicode %s" % unicodedata.unidata_version)


def number(value):
    """The text a float round-trips through, or '-' for a code point with no such property."""
    return "-" if value is None else repr(float(value))


def count(value):
    return "-" if value is None else str(value)


def probe(db, cp):
    char = chr(cp)
    try:
        numeric = db.numeric(char)
    except ValueError:
        numeric = None
    try:
        decimal = db.decimal(char)
    except ValueError:
        decimal = None
    try:
        digit = db.digit(char)
    except ValueError:
        digit = None
    return (
        db.category(char),
        db.combining(char),
        db.bidirectional(char),
        db.mirrored(char),
        db.east_asian_width(char),
        numeric,
        decimal,
        digit,
    )


def emit(db):
    previous = None
    start = 0
    ranges = []
    named = []
    named_start = None
    decomp = []
    for cp in range(0x110000):
        fields = probe(db, cp)
        if fields != previous:
            if previous is not None:
                ranges.append((start, cp - 1, previous))
            start = cp
            previous = fields
        try:
            db.name(chr(cp))
        except ValueError:
            if named_start is not None:
                named.append((named_start, cp - 1))
                named_start = None
        else:
            if named_start is None:
                named_start = cp
        text = db.decomposition(chr(cp))
        if text:
            decomp.append((cp, text))
    ranges.append((start, 0x10FFFF, previous))
    if named_start is not None:
        named.append((named_start, 0x10FFFF))

    # A composition pair exists for a character whose canonical decomposition is two code points and
    # which NFC rebuilds from its own NFD form; the round trip is also what drops the composition
    # exclusions and the non-starter decompositions, without transcribing a list.
    compose = []
    for cp in range(0x110000):
        text = db.decomposition(chr(cp))
        if not text or text.startswith("<"):
            continue
        parts = [int(piece, 16) for piece in text.split()]
        if len(parts) != 2:
            continue
        char = chr(cp)
        if db.normalize("NFC", db.normalize("NFD", char)) == char:
            compose.append((parts[0], parts[1], cp))

    lines = [
        "# Unicode %s for jy3, generated by runtime/tools/gen_unicode_320.py." % EXPECTED,
        "# source: CPython %d.%d unicodedata.ucd_3_2_0 (unidata_version %s)"
        % (*sys.version_info[:2], EXPECTED),
        "# names live in unicode-names.txt.gz (Unicode %s spells all of them identically);" % CURRENT,
        "# 'named' is the set of code points this version gives a name to.",
        "#",
        "# range LO-HI;CAT;CCC;BIDI;MIRROR;EAW;NUM;DEC;DIG",
        "# decomp HEX;TEXT",
        "# named LO-HI",
        "# compose A+B;C",
    ]
    for lo, hi, (cat, ccc, bidi, mirror, eaw, numeric, decimal, digit) in ranges:
        lines.append(
            "range %X-%X;%s;%d;%s;%d;%s;%s;%s;%s"
            % (
                lo,
                hi,
                cat,
                ccc,
                bidi,
                mirror,
                eaw,
                number(numeric),
                count(decimal),
                count(digit),
            )
        )
    lines.extend("decomp %X;%s" % (cp, text) for cp, text in decomp)
    lines.extend("named %X-%X" % (lo, hi) for lo, hi in named)
    lines.extend("compose %X+%X;%X" % (first, second, cp) for first, second, cp in compose)
    return "\n".join(lines) + "\n", len(ranges), len(decomp), len(named), len(compose)


def main() -> int:
    check()
    if len(sys.argv) != 2:
        print("usage: gen_unicode_320.py OUTPUT", file=sys.stderr)
        return 2
    text, ranges, decomp, named, compose = emit(unicodedata.ucd_3_2_0)
    raw = text.encode("ascii")
    buffer = io.BytesIO()
    with gzip.GzipFile(fileobj=buffer, mode="wb", mtime=0) as packed:
        packed.write(raw)
    with open(sys.argv[1], "wb") as handle:
        handle.write(buffer.getvalue())
    print(
        "%s: %d ranges, %d decompositions, %d named runs, %d composition pairs;"
        " %d bytes raw, %d bytes gzipped"
        % (sys.argv[1], ranges, decomp, named, compose, len(raw), len(buffer.getvalue())),
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
